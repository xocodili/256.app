-- Content ingestion foundation: domains + canonical links + safety/recrawl metadata.
-- Trust tier uses existing `status` ref group:
-- - pending_verification: low trust (default)
-- - flagged: suspicious
-- - blocked: never-use
-- - verified: trusted

CREATE TABLE content_domain (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    domain VARCHAR(255) NOT NULL COMMENT 'Registrable domain (lowercase, punycode-safe), e.g. youtube.com',
    status_id BIGINT UNSIGNED NOT NULL COMMENT 'FK ref_key_values.id, group status (acts as trust tier)',
    rating DECIMAL(3,2) NOT NULL DEFAULT 0.00 COMMENT 'Internal qualitative score, 0.00..5.00',
    first_seen_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_seen_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    safety_checked_at DATETIME(6) NULL,
    safety_state VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT 'pending|safe|suspicious|unsafe',
    safety_note TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by BIGINT UNSIGNED NULL,
    modified_by BIGINT UNSIGNED NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_content_domain_domain (domain),
    KEY idx_content_domain_status_rating (status_id, rating),
    KEY idx_content_domain_last_seen (last_seen_at),
    CONSTRAINT chk_content_domain_rating_range CHECK (rating >= 0.00 AND rating <= 5.00),
    CONSTRAINT chk_content_domain_safety_state CHECK (safety_state IN ('pending', 'safe', 'suspicious', 'unsafe')),
    CONSTRAINT fk_content_domain_status FOREIGN KEY (status_id) REFERENCES ref_key_values (id) ON DELETE RESTRICT,
    CONSTRAINT fk_content_domain_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_content_domain_modified_by FOREIGN KEY (modified_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE content_link (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    domain_id BIGINT UNSIGNED NOT NULL COMMENT 'FK content_domain.id',
    url_original TEXT NOT NULL COMMENT 'Immutable original user-provided URL for attribution',
    url_canonical VARCHAR(2048) NOT NULL COMMENT 'Canonical normalized URL used for dedupe + lookup',
    url_canonical_sha BINARY(32) NOT NULL COMMENT 'UNHEX(SHA2(url_canonical, 256)) for compact indexed dedupe',
    status_id BIGINT UNSIGNED NOT NULL COMMENT 'FK ref_key_values.id, group status (acts as trust tier)',
    rating DECIMAL(3,2) NOT NULL DEFAULT 0.00 COMMENT 'Internal qualitative score, 0.00..5.00',
    fetch_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT 'pending|ok|not_found|gone|error',
    fetch_attempts INT UNSIGNED NOT NULL DEFAULT 0,
    last_http_status SMALLINT UNSIGNED NULL,
    fetch_error TEXT NULL,
    fetched_at DATETIME(6) NULL,
    last_success_at DATETIME(6) NULL,
    next_recrawl_at DATETIME(6) NOT NULL DEFAULT (CURRENT_TIMESTAMP(6) + INTERVAL 6 HOUR),
    etag VARCHAR(512) NULL,
    last_modified_header VARCHAR(512) NULL,
    content_changed_at DATETIME(6) NULL COMMENT 'When metadata/content changed from a prior successful fetch',
    content_deleted_at DATETIME(6) NULL COMMENT 'When resource started returning deleted/not-found semantics',
    og_title VARCHAR(1024) NULL,
    og_description TEXT NULL,
    og_image_url VARCHAR(2048) NULL,
    og_site_name VARCHAR(512) NULL,
    og_type VARCHAR(128) NULL,
    og_url VARCHAR(2048) NULL,
    og_locale VARCHAR(64) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by BIGINT UNSIGNED NULL,
    modified_by BIGINT UNSIGNED NULL,
    PRIMARY KEY (id),
    KEY idx_content_link_url_canonical_prefix (url_canonical(512)),
    UNIQUE KEY uq_content_link_url_canonical_sha (url_canonical_sha),
    KEY idx_content_link_domain_status (domain_id, status_id),
    KEY idx_content_link_recrawl (next_recrawl_at, fetch_status),
    KEY idx_content_link_status_rating (status_id, rating),
    KEY idx_content_link_last_success (last_success_at),
    CONSTRAINT chk_content_link_rating_range CHECK (rating >= 0.00 AND rating <= 5.00),
    CONSTRAINT chk_content_link_fetch_status CHECK (fetch_status IN ('pending', 'ok', 'not_found', 'gone', 'error')),
    CONSTRAINT fk_content_link_domain FOREIGN KEY (domain_id) REFERENCES content_domain (id) ON DELETE CASCADE,
    CONSTRAINT fk_content_link_status FOREIGN KEY (status_id) REFERENCES ref_key_values (id) ON DELETE RESTRICT,
    CONSTRAINT fk_content_link_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_content_link_modified_by FOREIGN KEY (modified_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
