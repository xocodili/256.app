-- AI councillor content-domain portfolios (32 hosts each) + optional single profile link on non-AI entities.
-- Seeds one canonical content_link per portfolio host (https://{domain}/) for council content-share catalogue.

SET @verified_status := (
    SELECT id FROM ref_key_values WHERE `group` = 'status' AND `key` = 'verified' LIMIT 1
);
SET @seed_uid := (SELECT id FROM users WHERE email = 'system@256.app' LIMIT 1);

ALTER TABLE social_entity
    ADD COLUMN profile_content_link_id BIGINT UNSIGNED NULL
        COMMENT 'Optional single external URL for humans, communities, orgs, gatherings (not council AI)'
        AFTER location_id;

ALTER TABLE social_entity
    ADD CONSTRAINT fk_social_entity_profile_content_link
        FOREIGN KEY (profile_content_link_id) REFERENCES content_link (id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS ai_actor_content_domain (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ai_actor_id BIGINT UNSIGNED NOT NULL,
    content_domain_id BIGINT UNSIGNED NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    added_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    removed_at DATETIME(6) NULL,
    created_by BIGINT UNSIGNED NULL,
    modified_by BIGINT UNSIGNED NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_ai_actor_content_domain (ai_actor_id, content_domain_id),
    KEY idx_ai_actor_content_domain_domain (content_domain_id),
    KEY idx_ai_actor_content_domain_active (ai_actor_id, is_active),
    CONSTRAINT fk_ai_actor_content_domain_actor
        FOREIGN KEY (ai_actor_id) REFERENCES ai_actor (id) ON DELETE CASCADE,
    CONSTRAINT fk_ai_actor_content_domain_domain
        FOREIGN KEY (content_domain_id) REFERENCES content_domain (id) ON DELETE CASCADE,
    CONSTRAINT fk_ai_actor_content_domain_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_ai_actor_content_domain_modified_by
        FOREIGN KEY (modified_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

