INSERT INTO ai_actor_content_domain (
    ai_actor_id,
    content_domain_id,
    is_active,
    created_by,
    modified_by
)
SELECT
    aa.id,
    cd.id,
    1,
    @seed_uid,
    @seed_uid
FROM tmp_council_portfolio t
INNER JOIN ai_actor aa ON aa.slug = t.actor_slug AND aa.is_active = 1
INNER JOIN content_domain cd ON cd.domain = t.domain
LEFT JOIN ai_actor_content_domain existing
    ON existing.ai_actor_id = aa.id AND existing.content_domain_id = cd.id
WHERE existing.id IS NULL;

UPDATE content_domain cd
INNER JOIN tmp_council_portfolio t ON t.domain = cd.domain
SET cd.rating = 2.50,
    cd.safety_state = 'safe',
    cd.safety_checked_at = COALESCE(cd.safety_checked_at, UTC_TIMESTAMP(6))
WHERE cd.rating < 2.50;

INSERT INTO content_link (
    domain_id,
    url_original,
    url_canonical,
    url_canonical_sha,
    status_id,
    rating,
    fetch_status,
    fetched_at,
    last_success_at,
    created_by,
    modified_by
)
SELECT
    cd.id,
    CONCAT('https://', cd.domain, '/'),
    CONCAT('https://', cd.domain, '/'),
    UNHEX(SHA2(CONCAT('https://', cd.domain, '/'), 256)),
    @verified_status,
    2.50,
    'ok',
    UTC_TIMESTAMP(6),
    UTC_TIMESTAMP(6),
    @seed_uid,
    @seed_uid
FROM (
    SELECT DISTINCT domain FROM tmp_council_portfolio
) ports
INNER JOIN content_domain cd ON cd.domain = ports.domain
LEFT JOIN content_link cl
    ON cl.url_canonical_sha = UNHEX(SHA2(CONCAT('https://', cd.domain, '/'), 256))
WHERE cl.id IS NULL;

